const TABLES: Record<string, Table> = {
  en: EN,
  de: DE,
  ru: RU,
  es: ES,
  fr: FR,
  pt: PT,
  it: IT,
  nl: NL,
  pl: PL,
  tr: TR,
  uk: UK,
  ar: AR,
  zh: ZH,
  ja: JA,
  ko: KO,
};

export function tableFor(key: string): Table {
  return TABLES[key] ?? EN;
}

/** Share of the interface a language covers, 0-100, computed from the tables themselves. */
export function coverageOf(key: string): number {
  if (key === 'en') return 100;
  const table = TABLES[key];
  if (!table) return 0;
  const total = Object.keys(EN).length;
  const have = Object.keys(EN).filter((entry) => Boolean(table[entry])).length;
  return Math.round((100 * have) / total);
}

/** The languages that have a table, with their coverage. */
export function languagesWithCoverage(): (LanguageDef & { coverage: number })[] {
  return LANGUAGES.map((entry) => ({ ...entry, coverage: coverageOf(entry.key) }));
}

/**
 * One key in one language.
 *
 * The fallback chain is deliberate: the chosen table, then English, then the key itself. A
 * missing translation must never render as a blank label - a dialog with an empty button is
 * worse than one in the wrong language.
 */
export function translate(key: string, language: string): string {
  const table = TABLES[language];
  const value = table?.[key];
  if (value) return value;
  return EN[key] ?? key;
}

/** Every key the interface may ask for; the tests assert no caller invents one. */
export function allKeys(): string[] {
  return Object.keys(EN);
}

